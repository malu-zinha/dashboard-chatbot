-- =====================================================
-- EXPORTAR A ESTRUTURA DO BANCO (SO LEITURA)
-- =====================================================
-- Le o catalogo do Postgres e devolve, uma linha por objeto, o SQL que cria
-- a estrutura atual do schema public: extensoes, tipos, sequencias, tabelas,
-- restricoes, indices, funcoes, views, triggers, RLS, policies e permissoes.
-- NAO le nenhum dado das tabelas e NAO altera nada.
--
-- Como usar (SQL Editor do Supabase, fora da rede que bloqueia api.supabase.com):
--   1. Cole e rode (Run).
--   2. Em Results, Export -> Download CSV.
--   3. npx tsx scripts/montar-baseline.ts <arquivo.csv>
--      gera supabase/migrations/00000000_baseline.sql
--
-- Colunas: ordem (grupo), seq (ordem dentro do grupo), tipo, nome, ddl.
-- =====================================================

WITH
extensoes AS (
  SELECT 0 AS ordem, 0::bigint AS seq, 'extensao' AS tipo, e.extname::text AS nome,
         format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname) AS ddl
  FROM pg_extension e
  JOIN pg_namespace n ON n.oid = e.extnamespace
  WHERE e.extname <> 'plpgsql'
),
tipos AS (
  SELECT 1, t.oid::bigint, 'tipo', t.typname::text,
         format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
           (SELECT string_agg(quote_literal(en.enumlabel), ', ' ORDER BY en.enumsortorder)
            FROM pg_enum en WHERE en.enumtypid = t.oid))
  FROM pg_type t
  JOIN pg_namespace n ON n.oid = t.typnamespace
  WHERE n.nspname = 'public' AND t.typtype = 'e'
),
sequencias AS (
  SELECT 2, c.oid::bigint, 'sequencia', c.relname::text,
         format('CREATE SEQUENCE IF NOT EXISTS public.%I AS %s INCREMENT %s MINVALUE %s MAXVALUE %s START %s%s;',
           c.relname, format_type(s.seqtypid, NULL), s.seqincrement, s.seqmin, s.seqmax, s.seqstart,
           CASE WHEN s.seqcycle THEN ' CYCLE' ELSE '' END)
  FROM pg_sequence s
  JOIN pg_class c ON c.oid = s.seqrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
    -- sequencias de colunas IDENTITY nascem com a propria coluna
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'i')
),
tabelas AS (
  SELECT 3, c.oid::bigint, 'tabela', c.relname::text,
         format(E'CREATE TABLE public.%I (\n%s\n);', c.relname,
           (SELECT string_agg(
                     format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                       CASE a.attidentity
                         WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                         WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                         ELSE '' END,
                       CASE
                         WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                         WHEN ad.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
                         ELSE '' END,
                       CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END),
                     E',\n' ORDER BY a.attnum)
            FROM pg_attribute a
            LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
            WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped))
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
),
sequencias_donas AS (
  -- sequencias de colunas serial: "OWNED BY" depois que a tabela existe
  SELECT 3, c.oid::bigint + 1000000000, 'sequencia_dona', c.relname::text,
         format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', c.relname, t.relname, a.attname)
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  JOIN pg_depend d ON d.objid = c.oid AND d.deptype = 'a' AND d.refobjsubid > 0
  JOIN pg_class t ON t.oid = d.refobjid
  JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
  WHERE n.nspname = 'public' AND c.relkind = 'S'
),
restricoes AS (
  SELECT CASE WHEN con.contype = 'f' THEN 5 ELSE 4 END, con.oid::bigint, 'restricao',
         (c.relname || '.' || con.conname)::text,
         format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', c.relname, con.conname, pg_get_constraintdef(con.oid))
  FROM pg_constraint con
  JOIN pg_class c ON c.oid = con.conrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND con.contype IN ('p', 'u', 'f', 'c', 'x')
),
indices AS (
  SELECT 6, i.oid::bigint, 'indice', i.relname::text, pg_get_indexdef(i.oid) || ';'
  FROM pg_index x
  JOIN pg_class i ON i.oid = x.indexrelid
  JOIN pg_class c ON c.oid = x.indrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
    -- os que sustentam PK/UNIQUE/EXCLUDE nascem com a restricao
    AND NOT EXISTS (SELECT 1 FROM pg_constraint con
                    WHERE con.conindid = x.indexrelid AND con.contype IN ('p', 'u', 'x'))
),
funcoes AS (
  SELECT 7, p.oid::bigint, 'funcao', p.oid::regprocedure::text, pg_get_functiondef(p.oid) || ';'
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind IN ('f', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
),
visoes AS (
  -- oid crescente: uma view so pode existir depois das que ela usa
  SELECT 8, c.oid::bigint, CASE c.relkind WHEN 'm' THEN 'view_materializada' ELSE 'view' END, c.relname::text,
         format(E'CREATE %s public.%I%s AS\n%s',
           CASE c.relkind WHEN 'm' THEN 'MATERIALIZED VIEW' ELSE 'OR REPLACE VIEW' END,
           c.relname,
           CASE WHEN c.reloptions IS NOT NULL THEN ' WITH (' || array_to_string(c.reloptions, ', ') || ')' ELSE '' END,
           rtrim(pg_get_viewdef(c.oid, true), ';')
             || CASE c.relkind WHEN 'm' THEN E'\nWITH NO DATA;' ELSE ';' END)
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('v', 'm')
),
gatilhos AS (
  SELECT 9, t.oid::bigint, 'trigger', (c.relname || '.' || t.tgname)::text,
         pg_get_triggerdef(t.oid, true) || ';'
           || CASE t.tgenabled
                WHEN 'D' THEN format(E'\nALTER TABLE public.%I DISABLE TRIGGER %I;', c.relname, t.tgname)
                ELSE '' END
  FROM pg_trigger t
  JOIN pg_class c ON c.oid = t.tgrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND NOT t.tgisinternal
),
rls AS (
  SELECT 10, c.oid::bigint, 'rls', c.relname::text,
         format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', c.relname)
           || CASE WHEN c.relforcerowsecurity
                THEN format(E'\nALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', c.relname) ELSE '' END
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND c.relrowsecurity
),
politicas AS (
  SELECT 11, pol.oid::bigint, 'policy', (c.relname || '.' || pol.polname)::text,
         format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;',
           pol.polname, c.relname,
           CASE WHEN pol.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
           CASE pol.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE'
                           WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
           CASE WHEN pol.polroles = '{0}' THEN 'PUBLIC'
                ELSE (SELECT string_agg(quote_ident(rolname), ', ' ORDER BY rolname)
                      FROM pg_roles WHERE oid = ANY (pol.polroles)) END,
           CASE WHEN pol.polqual IS NOT NULL
                THEN ' USING (' || pg_get_expr(pol.polqual, pol.polrelid) || ')' ELSE '' END,
           CASE WHEN pol.polwithcheck IS NOT NULL
                THEN ' WITH CHECK (' || pg_get_expr(pol.polwithcheck, pol.polrelid) || ')' ELSE '' END)
  FROM pg_policy pol
  JOIN pg_class c ON c.oid = pol.polrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
),
-- Permissoes: primeiro tira tudo dos papeis da API, depois devolve o que vale hoje.
grants_rel AS (
  SELECT 12, c.oid::bigint, 'permissao', c.relname::text,
         format('REVOKE ALL ON %s public.%I FROM PUBLIC, anon, authenticated, service_role;',
                CASE c.relkind WHEN 'S' THEN 'SEQUENCE' ELSE 'TABLE' END, c.relname)
           || coalesce((
                SELECT string_agg(g.linha, '' ORDER BY g.linha)
                FROM (
                  SELECT format(E'\nGRANT %s ON %s public.%I TO %s;',
                           string_agg(a.privilege_type, ', ' ORDER BY a.privilege_type),
                           CASE c.relkind WHEN 'S' THEN 'SEQUENCE' ELSE 'TABLE' END, c.relname,
                           CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(a.grantee)) END) AS linha
                  FROM aclexplode(c.relacl) a
                  WHERE a.grantee = 0 OR pg_get_userbyid(a.grantee) IN ('anon', 'authenticated', 'service_role')
                  GROUP BY a.grantee
                ) g), '')
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm', 'S') AND c.relacl IS NOT NULL
),
grants_func AS (
  SELECT 13, p.oid::bigint, 'permissao', p.oid::regprocedure::text,
         format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated, service_role;', p.oid::regprocedure)
           || coalesce((
                SELECT string_agg(format(E'\nGRANT EXECUTE ON FUNCTION %s TO %s;', p.oid::regprocedure,
                         CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(a.grantee)) END),
                       '' ORDER BY a.grantee)
                FROM aclexplode(p.proacl) a
                WHERE a.privilege_type = 'EXECUTE'
                  AND (a.grantee = 0 OR pg_get_userbyid(a.grantee) IN ('anon', 'authenticated', 'service_role'))), '')
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind IN ('f', 'p') AND p.proacl IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
),
privilegios_padrao AS (
  -- registro do ALTER DEFAULT PRIVILEGES vigente (so documenta; ver 20261022)
  SELECT 14, d.oid::bigint, 'privilegio_padrao',
         (pg_get_userbyid(d.defaclrole) || ' ' || d.defaclobjtype::text),
         format('-- default privileges de %s em %s para objetos %s: %s',
           pg_get_userbyid(d.defaclrole), coalesce(n.nspname, '(todos os schemas)'),
           CASE d.defaclobjtype WHEN 'r' THEN 'tabela' WHEN 'S' THEN 'sequencia' WHEN 'f' THEN 'funcao'
                                WHEN 'T' THEN 'tipo' WHEN 'n' THEN 'schema' ELSE d.defaclobjtype::text END,
           d.defaclacl::text)
  FROM pg_default_acl d
  LEFT JOIN pg_namespace n ON n.oid = d.defaclnamespace
  WHERE n.nspname = 'public' OR d.defaclnamespace = 0
)
SELECT * FROM extensoes
UNION ALL SELECT * FROM tipos
UNION ALL SELECT * FROM sequencias
UNION ALL SELECT * FROM tabelas
UNION ALL SELECT * FROM sequencias_donas
UNION ALL SELECT * FROM restricoes
UNION ALL SELECT * FROM indices
UNION ALL SELECT * FROM funcoes
UNION ALL SELECT * FROM visoes
UNION ALL SELECT * FROM gatilhos
UNION ALL SELECT * FROM rls
UNION ALL SELECT * FROM politicas
UNION ALL SELECT * FROM grants_rel
UNION ALL SELECT * FROM grants_func
UNION ALL SELECT * FROM privilegios_padrao
ORDER BY ordem, seq, nome;
